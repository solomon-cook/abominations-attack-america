import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const source = "docs/authoritative-board-human-audit.md";
const target = "packages/game-engine/src/audited-board-data.ts";
const markdown = await readFile(source, "utf8");
const cells = [];
for (const [index, line] of markdown.split("\n").entries()) {
  if (!/^\| `\d+\/\d+`/.test(line)) continue;
  const values = line.trim().slice(1, -1).split("|").map((value) => value.trim().replaceAll("`", ""));
  const [row, column] = values[0].split("/").map(Number);
  if (values.length !== 6 && values.length !== 8) throw new Error(`Unexpected audit columns at line ${index + 1}`);
  const [tile, coastline, orientation, barriers, crop, features, status] = values.length === 8
    ? values.slice(1) : [values[1], "None", "None", ...values.slice(2)];
  if (status !== "Human verified") throw new Error(`Unverified audit cell ${values[0]}`);
  cells.push({ row, column, tile, coastline, orientation, barriers, crop, features, sourceRef: `${source}#L${index + 1}` });
}
if (cells.length !== 336 || new Set(cells.map(({row, column}) => `${row}/${column}`)).size !== 336) throw new Error("Audit must contain 336 unique cells");
for (let row = 0; row < 14; row++) for (let column = 0; column < 24; column++) {
  if (!cells.some((cell) => cell.row === row && cell.column === column)) throw new Error(`Missing ${row}/${column}`);
}
const output = `// Generated by scripts/generate-audited-board.mjs from the human audit. Do not edit.\nexport const AUDIT_SOURCE_SHA256 = ${JSON.stringify(createHash("sha256").update(markdown).digest("hex"))};\nexport const AUDITED_CELLS = ${JSON.stringify(cells, null, 2)} as const;\n`;
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== output) throw new Error("Audited board data is stale; run node scripts/generate-audited-board.mjs");
} else await writeFile(target, output);
console.log(`Verified ${cells.length} human-audited cells.`);
