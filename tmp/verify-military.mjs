import { chromium } from 'playwright';
import { chromePath } from '../scripts/chrome-path.mjs';
const browser=await chromium.launch({executablePath:chromePath,headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.on('pageerror',console.error);
await page.addInitScript(()=>localStorage.setItem('abominations-onboarding-seen','1'));
await page.goto('http://127.0.0.1:5191');
await page.getByRole('button',{name:'Play audited board',exact:true}).click();
for(let i=0;i<8;i++) {
 const setup=page.locator('.setup-options');
 if(!await setup.count()) break;
 const deploy=setup.getByRole('button',{name:'Deploy units',exact:true});
 await (await deploy.count()?deploy:setup.locator('button').first()).click();
 await page.waitForTimeout(150);
}
await page.getByRole('button',{name:'Show details',exact:true}).first().click();
const movable = page.locator('.unit-card button:not([disabled])').first();
const unitName = await movable.textContent();
await movable.click();
const piece = page.locator('.selected-piece').first();
await page.getByRole('button',{name:'Hide details',exact:true}).click();
await piece.evaluate(el=>el.click());
const target=page.locator('.hex-tile.legal').first();
await target.evaluate(el=>el.click());
await page.getByRole('button',{name:'Confirm unit move',exact:true}).first().click();
await page.waitForTimeout(200);
console.log('Military movement confirmed:',unitName);
await page.getByRole('button',{name:'Show details',exact:true}).first().click();
await page.getByRole('button',{name:'Leave monster here & finish Move',exact:true}).click();
await page.waitForTimeout(200);
for (let i=0;i<6;i++) {
 if(await page.getByRole('button',{name:'Deploy military',exact:true}).count()) break;
 const resolve=page.getByRole('button',{name:/^Resolve (fight|encounter)$/i}).first();
 if(await resolve.count()) { await resolve.click(); await page.waitForTimeout(200); } else break;
}
await page.getByRole('button',{name:'Deploy military',exact:true}).click();
await page.getByRole('dialog',{name:'Navy',exact:true}).waitFor();
const missing=await page.locator('.military-sheet img').evaluateAll(imgs=>imgs.filter(img=>!img.complete||!img.naturalWidth).map(img=>img.src));
await page.screenshot({path:'tmp/military-sheet.png'});
const reserve=page.getByRole('region',{name:'Reserve pieces'}).locator('button').last();
const chosenType=await reserve.locator('strong').textContent();
await reserve.click();
const glow=page.locator('.deployment-legal');
if(!await glow.count()) throw Error('No deployment highlights');
await page.screenshot({path:'tmp/military-glow.png'});
const destination=await glow.first().getAttribute('data-hex-key');
const before=await glow.first().locator('.tile-piece').count();
await glow.first().evaluate(el=>el.click());
await page.waitForTimeout(300);
const placed=page.locator(`[data-hex-key="${destination}"] .tile-piece`);
if(await placed.count()!==before+1) throw Error('Piece not placed');
console.log('Deployment verified:',chosenType,'at',destination,'missing artwork:',missing);
await page.getByRole('button',{name:'Deploy military',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'tmp/military-sheet-mobile.png'});
await page.keyboard.press('Escape');
if(await page.locator('.military-sheet').count()) throw Error('Escape did not dismiss sheet');
console.log('Mobile sheet and Escape dismissal verified');
await browser.close();
